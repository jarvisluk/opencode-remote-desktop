// OpenCode Desktop looks up `catalog[locale]` directly without BCP-47 prefix fallback,
// so include both OpenCode's short codes ("zh", "zht") and standard BCP-47 aliases.
export const guiCatalog: Catalog = {
  en: guiEn,
  zh: guiZh,
  "zh-CN": guiZh,
  "zh-Hans": guiZh,
  zht: guiZht,
  "zh-TW": guiZht,
  "zh-HK": guiZht,
  "zh-Hant": guiZht,
}

const TABLES: Record<SupportedLocale, Record<GuiMessageKey, string>> = {
  en: guiEn,
  zh: guiZh,
  zht: guiZht,
}

/** Creates a standalone translator (used in tests or when rendering outside OpenCode GUI context). */
export function createGuiTranslator(locale?: string): GuiTranslate {
  const normalized = normalizeLocale(locale)
  const table = TABLES[normalized]
  return (key, params) => {
    const template = (table as Record<string, string>)[key] ?? (guiEn as Record<string, string>)[key] ?? key
    return interpolate(template, params)
  }
}
